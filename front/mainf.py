    def on_live_data(self, data):
        def clamp_temp(v):
            """Защита от uint32 переполнения в C++ (A-40 при unsigned)."""
            v = float(v)
            return round(v) if -40 <= v <= 215 else "—"

        def fmt(v, decimals=0):
            try:
                return f"{round(float(v), decimals)}" if decimals else f"{round(float(v))}"
            except Exception:
                return "—"

        if "rpm" in data:
            self.live_labels["rpm"].setText(f"{fmt(data['rpm'])} об/мин")
        if "speed" in data:
            self.live_labels["speed"].setText(f"{fmt(data['speed'])} км/ч")
        if "coolant" in data:
            self.live_labels["coolant"].setText(f"{clamp_temp(data['coolant'])}°C")
        if "throttle" in data:
            v = max(0.0, min(100.0, float(data['throttle'])))
            self.live_labels["throttle"].setText(f"{round(v, 1)}%")
        if "voltage" in data:
            self.live_labels["voltage"].setText(f"{fmt(data['voltage'], 1)}V")
        if "maf" in data:
            self.live_labels["maf"].setText(f"{fmt(data['maf'], 2)} г/с")
        if "intake" in data:
            self.live_labels["intake"].setText(f"{clamp_temp(data['intake'])}°C")
        if "fuel_pressure" in data:
            self.live_labels["fuel_pressure"].setText(f"{fmt(data['fuel_pressure'])} кПа")
        
        self.status_widget.on_data_received()
    
