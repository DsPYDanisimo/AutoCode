    def update_status(self, status_data):
        """Обновление статуса из данных API"""
        connected = status_data.get("connected", False)
        
        if connected:
            self.status_indicator.setText("🟢")
            self.status_indicator.setStyleSheet("color: #00FF00;")
            
            self.status_text.setText("✅ ПОДКЛЮЧЕНО")
            self.status_text.setStyleSheet("color: green; font-weight: bold; font-size: 14px;")
            
            protocol = status_data.get("protocol", "OBD-II")
            port = status_data.get("port", "N/A")
            ecu_type = status_data.get("ecu_type", "ECU")
            
            self.details_text.setText(f"Порт: {port} | Протокол: {protocol} | ЭБУ: {ecu_type}")
            
            if "connected_for" in status_data:
                self.connection_time.setText(status_data["connected_for"])
            
            quality = status_data.get("signal_quality", 50)
            self.quality_bar.setValue(quality)
            
            if quality >= 80:
                self.quality_bar.setStyleSheet("QProgressBar::chunk { background-color: #4CAF50; }")
            elif quality >= 50:
                self.quality_bar.setStyleSheet("QProgressBar::chunk { background-color: #FFC107; }")
            else:
                self.quality_bar.setStyleSheet("QProgressBar::chunk { background-color: #F44336; }")
                
        else:
            self.status_indicator.setText("🔴")
            self.status_indicator.setStyleSheet("color: #FF0000;")
            
            self.status_text.setText("❌ НЕТ ПОДКЛЮЧЕНИЯ")
            self.status_text.setStyleSheet("color: red; font-weight: bold; font-size: 14px;")
            
            self.details_text.setText("Порт: Не выбран | Протокол: Н/Д")
            self.connection_time.setText("00:00:00")
            self.quality_bar.setValue(0)
            
            self.packet_count = 0
            self.packets_label.setText("0 пакетов")
    
    def blink_activity(self):
        """Мигание индикатора активности"""
        if self.packet_count > 0:
            if self.activity_state:
                self.activity_led.setStyleSheet("color: #4CAF50; font-size: 18px;")
            else:
                self.activity_led.setStyleSheet("color: #00FF00; font-size: 18px;")
            self.activity_state = not self.activity_state
        else:
            self.activity_led.setStyleSheet("color: gray; font-size: 18px;")
    
    def on_data_received(self):
        """Вызывается при получении данных"""
        self.packet_count += 1
        self.packets_label.setText(f"{self.packet_count} пакетов")
    
    def reset_packet_count(self):
        """Сброс счетчика пакетов при отключении"""
        self.packet_count = 0
        self.packets_label.setText("0 пакетов")


