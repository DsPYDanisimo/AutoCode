    def filter_ports_by_type(self, port_type):
        self.port_combo.clear()
        self.port_combo.setEnabled(True)

        # При Bluetooth: скрываем 🔄 (дублирует сканирование), показываем кнопку BT-сканирования
        is_bt    = port_type == "Bluetooth"
        is_j2534 = port_type == "J2534/PassThru"
        self.port_refresh_btn.setVisible(not is_bt and not is_j2534)
        self.bt_scan_btn.setVisible(is_bt)
        self.j2534_scan_btn.setVisible(is_j2534)

        if not self.all_ports:
            self.port_combo.addItem("Нет доступных портов")
            return

        type_map = {
            "Все":           None,
            "Serial (COM)":  "serial",
            "TCP/IP":        "tcp",
            "Bluetooth":     "bluetooth",
            "J2534/PassThru": "j2534",
        }

        filter_type = type_map.get(port_type)

        for port_info in self.all_ports:
            if filter_type is None or port_info.get("type") == filter_type:
                icon = self.get_port_icon(port_info.get("type"))
                paired_mark = "" if port_info.get("paired", True) else " ⚠ не спарено"
                display_text = (f"{icon} {port_info.get('name')} - "
                                f"{port_info.get('description', '')}{paired_mark}")
                self.port_combo.addItem(display_text, port_info)
    
    def get_port_icon(self, port_type):
        icons = {
            "serial":    "🔌",
            "tcp":       "🌐",
            "bluetooth": "📡",
            "usb":       "💻",
            "j2534":     "🔧",
        }
        return icons.get(port_type, "🔌")
    
    def connect_to_ecu(self):
        try:
            if self.port_combo.count() == 0 or self.port_combo.currentText() == "Нет доступных портов":
                QMessageBox.warning(self, "Ошибка", "Нет доступных портов для подключения")
                return
            
            port_info = self.port_combo.currentData()
            if not port_info:
                port_text = self.port_combo.currentText().split(" - ")[0].strip()
                # Убираем иконку-emoji в начале (1 символ + пробел)
                if port_text and not port_text[0].isascii():
                    port_text = port_text[2:].strip()
                port_info = {"name": port_text, "type": "serial"}

            # J2534: baud rate и тип протокола выбираются автоматически
            if port_info.get("type") == "j2534":
                port_info = dict(port_info)   # не мутируем оригинал
                # baud_rate/protocol игнорируются в connect_to_j2534,
                # но передаём для единообразия
                port_info["baud_rate"] = 0

            # Bluetooth: проверить, спарено ли устройство
            if port_info.get("type") == "bluetooth":
                if not port_info.get("paired", True):
                    QMessageBox.warning(
                        self, "Bluetooth — устройство не спарено",
                        f"Устройство «{port_info.get('description', port_info.get('name'))}» "
                        f"не спарено с компьютером.\n\n"
                        "Сначала добавьте адаптер через:\n"
                        "Параметры Windows → Bluetooth и другие устройства"
                    )
                    return
                # Спаренный BT-адаптер работает через COM-порт — передаём бэкенду как serial
                port_info = dict(port_info)
                port_info["type"] = "serial"

            protocol = self.protocol_combo.currentText()
            baud_rate = int(self.baud_combo.currentText())
            
            if protocol != "Автоопределение":
                port_info["protocol"] = protocol
            port_info["baud_rate"] = baud_rate
            
            # Блокируем кнопки на время подключения
            self.connect_btn.setEnabled(False)
            self.port_combo.setEnabled(False)
            self.protocol_combo.setEnabled(False)
            self.baud_combo.setEnabled(False)
            
            logger.info(f"Попытка подключения к {port_info.get('name')}")
            self.log_event(f"Попытка подключения к {port_info['name']}...")
            self.progress_bar.setVisible(True)
            self.progress_bar.setValue(10)
            
            # Запускаем подключение в отдельном потоке
            # Все GUI-операции делаем через сигнал _connect_done (thread-safe)
            def connect_thread():
                error_msg = ""
                success = False
                try:
                    result = self.api_client.connect_to_port(port_info)
                    if result.get("success"):
                        logger.info("Подключение успешно")
                        success = True
                    else:
                        error_msg = result.get("error", "Неизвестная ошибка")
                        logger.error(f"Ошибка подключения: {error_msg}")
                except Exception as e:
                    logger.exception("Критическая ошибка")
                    error_msg = str(e)
                finally:
                    self._connect_done.emit(success, error_msg)
            
            thread = threading.Thread(target=connect_thread, daemon=True)
            thread.start()
            
        except Exception as e:
            logger.exception("Критическая ошибка")
            self.log_event(f"❌ Ошибка: {str(e)}")
            QMessageBox.critical(self, "Ошибка", f"Не удалось подключиться: {str(e)}")
            self.progress_bar.setVisible(False)
            self.connect_btn.setEnabled(True)
            self.port_combo.setEnabled(True)
            self.protocol_combo.setEnabled(True)
            self.baud_combo.setEnabled(True)
    
