    def load_dtc_from_api(self):
        """Загрузка DTC кодов из базы данных через API"""
        try:
            import requests
            response = requests.get(f"{self.api_client.base_url}/dtc/all", timeout=3)
            if response.status_code == 200:
                dtc_list = response.json()
                self.populate_table(dtc_list)
                logger.info(f"Загружено {len(dtc_list)} DTC кодов из базы")
            else:
                self.load_default_dtc()
        except Exception as e:
            logger.error(f"Ошибка загрузки DTC из API: {e}")
            self.load_default_dtc()
    
    def populate_table(self, dtc_list):
        """Заполнение таблицы данными"""
        self.dtc_table.setRowCount(len(dtc_list))
        for i, dtc in enumerate(dtc_list):
            self.dtc_table.setItem(i, 0, QTableWidgetItem(dtc.get("code", "")))
            self.dtc_table.setItem(i, 1, QTableWidgetItem(dtc.get("description", "")))
            self.dtc_table.setItem(i, 2, QTableWidgetItem(dtc.get("system_type", "")))
            
            causes = dtc.get("possible_causes", [])
            causes_str = ", ".join(causes[:3]) if isinstance(causes, list) else str(causes)
            self.dtc_table.setItem(i, 3, QTableWidgetItem(causes_str))
            
            severity = dtc.get("severity", 0)
            severity_item = QTableWidgetItem(str(severity) if severity else "—")
            severity_item.setTextAlignment(Qt.AlignCenter)
            severity_item.setForeground(QColor(0, 0, 0))
            font = severity_item.font()
            font.setBold(True)
            severity_item.setFont(font)
            if severity >= 4:
                severity_item.setBackground(QColor(255, 120, 120))   # красный
            elif severity >= 3:
                severity_item.setBackground(QColor(255, 210, 80))    # жёлтый
            elif severity >= 1:
                severity_item.setBackground(QColor(120, 210, 120))   # зелёный
            self.dtc_table.setItem(i, 4, severity_item)
    
    def load_default_dtc(self):
        """Загружает встроенную базу DTC (используется когда API недоступен)."""
        self._populate_from_db(_DTC_DB)

    def _populate_from_db(self, db: dict):
        """Заполняет таблицу из словаря _DTC_DB."""
        rows = sorted(db.items())   # сортировка по коду
        self.dtc_table.setSortingEnabled(False)
        self.dtc_table.setRowCount(len(rows))

        SEV_LABELS = {5: "Критическая", 4: "Высокая", 3: "Средняя", 2: "Низкая", 1: "Инфо"}

        for i, (code, entry) in enumerate(rows):
            self.dtc_table.setItem(i, 0, QTableWidgetItem(code))
            self.dtc_table.setItem(i, 1, QTableWidgetItem(entry.get("ru", "")))
            self.dtc_table.setItem(i, 2, QTableWidgetItem(entry.get("system", "")))

            causes = entry.get("causes", [])
            causes_str = "; ".join(causes[:3]) if causes else "—"
            causes_item = QTableWidgetItem(causes_str)
            if causes:
                causes_item.setToolTip("Возможные причины:\n• " + "\n• ".join(causes))
            self.dtc_table.setItem(i, 3, causes_item)

            sev = entry.get("severity", 0)
            sev_label = SEV_LABELS.get(sev, "—")
            sev_item = QTableWidgetItem(sev_label)
            sev_item.setTextAlignment(Qt.AlignCenter)
            if sev in _SEV_COLORS:
                bg, fg, _ = _SEV_COLORS[sev]
                sev_item.setBackground(bg)
                sev_item.setForeground(fg)
            self.dtc_table.setItem(i, 4, sev_item)

        self.dtc_table.setSortingEnabled(True)
    
    def search_dtc(self):
        """Поиск по базе DTC — сначала API, при ошибке — локальная база."""
        query = self.search_input.text().strip()
        if not query:
            self.load_dtc_from_api()
            return

        try:
            import requests
            response = requests.get(
                f"{self.api_client.base_url}/dtc/search?query={quote(query)}", timeout=3)
            if response.status_code == 200:
                results = response.json()
                self.populate_table(results)
                logger.info(f"Поиск DTC: '{query}' — найдено {len(results)}")
                return
        except Exception:
            pass

        # Локальный поиск по _DTC_DB
        q = query.lower()
        matched = {
            code: entry for code, entry in _DTC_DB.items()
            if q in code.lower() or q in entry.get("ru", "").lower()
               or any(q in c.lower() for c in entry.get("causes", []))
        }
        self._populate_from_db(matched)
        logger.info(f"Поиск DTC (локально): '{query}' — найдено {len(matched)}")


