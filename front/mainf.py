        info = self.api_client.get_ecu_info()
        if not info:
            self.info_text.setHtml(
                f"<div style='{_CSS}'><span style='color:#888;'>Информация не доступна</span></div>"
            )
            return

        # Нормализуем ключи HTTP-бэкенда
        _key_map = {
            "vin":            "VIN",
            "ecu_type":       "ecu_type",
            "calibration_id": "calibration_id",
            "ecu_name":       "ecu_name",
            "serial":         "serial",
            "sw_id":          "sw_id",
            "part_number":    "part_number",
            "hw_type":        "hw_type",
            "dtc_count":      "dtc_count",
            "current_rpm":    "current_rpm",
            "current_speed":  "current_speed",
            "nodes":          "nodes",
            "dids":           "dids",
            "protocol":       "protocol",
        }
        raw: dict = {}
        for k, v in info.items():
            raw[_key_map.get(k, k)] = str(v) if v is not None else ""

        # Извлекаем поля
        def _g(key, default="—"):
            v = raw.get(key, "")
            return v if v and v not in ("None", "null", "0", "") else default

        vin            = _g("VIN")
        ecu_type       = _g("ecu_type")
        calibration_id = _g("calibration_id")
        ecu_name       = _g("ecu_name")
        serial         = _g("serial")
        sw_id          = _g("sw_id")
        part_number    = _g("part_number")
        hw_type        = _g("hw_type")
        dtc_count      = _g("dtc_count", "0")
        current_rpm    = _g("current_rpm")
        current_speed  = _g("current_speed")
        interface_raw  = _g("Интерфейс")
        protocol       = _g("protocol", _g("Протокол"))
        fw_version     = _g("Прошивка адаптера")
        dll_version    = _g("Версия DLL")
        api_version    = _g("Версия API")

        # Адаптер/модель из строки интерфейса
        adapter_name = interface_raw if interface_raw != "—" else "ELM327"

        # Ошибки
        try:
            dtc_int = int(dtc_count)
        except ValueError:
            dtc_int = 0
        dtc_str = "Нет" if dtc_int == 0 else f"{dtc_int} активных"

        # ── Строители HTML ─────────────────────────────────────────────────
        def kv(label, value):
            """Одна строка 'Метка: Значение'."""
            if value in ("—", "", None):
                return ""
            return (
                f"{label}: "
                f"<span style='font-weight:600;'>{value}</span><br>"
            )

        def section_hdr(text):
            """Заголовок раздела — полужирный, без лишних отступов."""
            return f"<b>{text}</b><br>"

        def module_hdr(code, description):
            return (
                f"<span style='font-size:12px; font-weight:700; color:#5b9bd5;'>"
                f"{code} - {description}</span><br>"
            )

        def separator():
            return "<br>"

        # ── Сборка HTML ────────────────────────────────────────────────────
        parts = [f"<div style='{_CSS}'>"]

        # ── Раздел: Интерфейс ──────────────────────────────────────────────
        parts.append(section_hdr("Интерфейс:"))
        parts.append(kv("Адаптер", adapter_name))
        if fw_version != "—":
            parts.append(kv("Прошивка адаптера", fw_version))
        if dll_version != "—":
            parts.append(kv("Версия DLL", dll_version))
        if api_version != "—":
            parts.append(kv("Версия API", api_version))
        parts.append(kv("Протокол", protocol))
        parts.append(kv("Ошибки", dtc_str))
        parts.append(separator())

        # ── Раздел: Автомобиль ─────────────────────────────────────────────
        parts.append(section_hdr("Автомобиль:"))
        if ecu_type not in ("—", ""):
            parts.append(kv("Тип ЭБУ", ecu_type))
        if current_rpm not in ("—", ""):
            parts.append(kv("Текущие обороты", f"{current_rpm} об/мин"))
        if current_speed not in ("—", ""):
            parts.append(kv("Текущая скорость", f"{current_speed} км/ч"))
        if vin != "—":
            parts.append(kv("VIN", vin))
        parts.append(separator())

        # ── Раздел: Модули ЭБУ (OBD-II / PCM) ────────────────────────────
        parts.append(module_hdr("OBD2_PCM", "Бортовая диагностика OBD II (PCM)"))
        parts.append(separator())

        parts.append(module_hdr("PCM", "Модуль управления силовым агрегатом"))
        if part_number != "—":
            parts.append(kv("Номер детали", part_number))
