    def _on_read_errors_done(self, errors: list):
        """Вызывается в главном потоке после завершения чтения DTC."""
        import re as _re

        self.progress_bar.setRange(0, 100)
        self.progress_bar.setValue(100)
        QTimer.singleShot(400, lambda: self.progress_bar.setVisible(False))

        for btn in (self.read_errors_btn, self.clear_errors_btn):
            btn.setEnabled(True)

        if not errors:
            self._all_dtc_errors = []
            self.errors_table.setSortingEnabled(False)
            self.errors_table.setRowCount(1)
            self.errors_table.setItem(0, 1, QTableWidgetItem("Ошибок не найдено"))
            self._dtc_count_label.setText("Ошибок не найдено")
            logger.info("Ошибок не найдено")
            return

        # ── Обогащаем каждый DTC данными из базы _DTC_DB ─────────────────────
        enriched = []
        for err in errors:
            code       = err.get("code", "")
            desc_raw   = err.get("description", "")

            # Имя модуля из описания "DTC P0xxx [PCM] (статус: 0x28)"
            m = _re.search(r'\[([A-Za-z0-9_]+)\]', desc_raw)
            module = m.group(1) if m else "-"

            # Система по префиксу кода
            prefix = code[0].upper() if code else "P"
            system = _SYS_PREFIX_RU.get(prefix, "Неизвестно")

            # Данные из базы (база хранит коды без суб-типа, напр. "P0674" а не "P0674:00")
            base_code = code.split(":")[0]
            db = _DTC_DB.get(base_code, {})
            desc_ru  = db.get("ru", f"Неизвестный код {base_code}")
            severity = db.get("severity", 0)
            causes   = db.get("causes", [])
            db_sys   = db.get("system", system)  # уточнённая система из базы

            enriched.append({
                **err,
                "_module":   module,
                "_system":   db_sys,
                "_severity": severity,
                "_desc_ru":  desc_ru,
                "_causes":   causes,
            })

        self._all_dtc_errors = enriched

        # Сбрасываем фильтры и отображаем
        self._dtc_status_filter.blockSignals(True)
        self._dtc_system_filter.blockSignals(True)
        self._dtc_status_filter.setCurrentIndex(0)
        self._dtc_system_filter.setCurrentIndex(0)
        self._dtc_search.blockSignals(True)
        self._dtc_search.clear()
        self._dtc_search.blockSignals(False)
        self._dtc_status_filter.blockSignals(False)
        self._dtc_system_filter.blockSignals(False)

        self._apply_dtc_filter()

        logger.info(f"Получено ошибок: {len(errors)}")
        self.log_event(f"📋 Получено ошибок: {len(errors)}")

    def _apply_dtc_filter(self):
        """Фильтрует self._all_dtc_errors и перерисовывает таблицу."""
        status_f = self._dtc_status_filter.currentText()
        system_f = self._dtc_system_filter.currentText()
        search_f = self._dtc_search.text().strip().lower()

        filtered = []
        for err in self._all_dtc_errors:
            if status_f != "Все" and err.get("status", "") != status_f:
                continue
            if system_f != "Все" and err.get("_system", "") != system_f:
                continue
            if search_f:
                haystack = (err.get("code", "") + " " + err.get("_desc_ru", "")).lower()
                if search_f not in haystack:
                    continue
            filtered.append(err)

        # ── Заполнение таблицы ────────────────────────────────────────────────
        self.errors_table.setSortingEnabled(False)   # отключаем на время заполнения!
        self.errors_table.setRowCount(len(filtered))

        for i, err in enumerate(filtered):
            code     = err.get("code", "")
            status   = err.get("status", "Stored")
            module   = err.get("_module", "-")
            system   = err.get("_system", "")
            severity = err.get("_severity", 0)
            desc_ru  = err.get("_desc_ru", f"DTC {code}")
            causes   = err.get("_causes", [])

            # ── Столбец 0: Код ────────────────────────────────────────────────
            self.errors_table.setItem(i, 0, QTableWidgetItem(code))

            # ── Столбец 1: Описание + tooltip с причинами ─────────────────────
            desc_item = QTableWidgetItem(desc_ru)
            if causes:
                desc_item.setToolTip("Возможные причины:\n• " + "\n• ".join(causes))
            self.errors_table.setItem(i, 1, desc_item)

            # ── Столбец 2: Статус (цветной) ───────────────────────────────────
            status_item = QTableWidgetItem(status)
            if status in _STATUS_COLORS:
                bg, fg = _STATUS_COLORS[status]
                status_item.setBackground(bg)
                status_item.setForeground(fg)
            status_item.setTextAlignment(Qt.AlignCenter)
            self.errors_table.setItem(i, 2, status_item)

            # ── Столбец 3: Источник (модуль) ──────────────────────────────────
            mod_item = QTableWidgetItem(module)
            mod_item.setTextAlignment(Qt.AlignCenter)
            self.errors_table.setItem(i, 3, mod_item)

            # ── Столбец 4: Система ────────────────────────────────────────────
            self.errors_table.setItem(i, 4, QTableWidgetItem(system))

            # ── Столбец 5: Тяжесть (цветной) ─────────────────────────────────
            if severity in _SEV_COLORS:
                bg, fg, label = _SEV_COLORS[severity]
                sev_item = QTableWidgetItem(label)
                sev_item.setBackground(bg)
                sev_item.setForeground(fg)
            else:
                sev_item = QTableWidgetItem("—")
            sev_item.setTextAlignment(Qt.AlignCenter)
            self.errors_table.setItem(i, 5, sev_item)

        self.errors_table.setSortingEnabled(True)   # включаем после заполнения

        total  = len(self._all_dtc_errors)
        shown  = len(filtered)
        self._dtc_count_label.setText(
            self._tr["dtc_shown"].format(shown=shown, total=total) if shown != total
            else self._tr["dtc_total"].format(total=total)
        )
    
